const getLocalizedScheme = (scheme, lang = "en") => {
  if (!scheme) return scheme;
  if (!lang || lang === "en") return scheme;

  const langData = SCHEME_TRANSLATIONS[lang] || SCHEME_TRANSLATIONS["te"];
  if (!langData) return scheme;

  const key =
    Object.keys(langData).find(
      (k) =>
        (scheme.name && scheme.name.toLowerCase().includes(k.toLowerCase())) ||
        (scheme.full_name && scheme.full_name.toLowerCase().includes(k.toLowerCase())) ||
        (scheme.short_name && scheme.short_name.toLowerCase().includes(k.toLowerCase())) ||
        (scheme.shortName && scheme.shortName.toLowerCase().includes(k.toLowerCase()))
    );

  if (!key || !langData[key]) {
    return scheme;
  }

  const t = langData[key];
  return {
    ...scheme,
    original_category: scheme.category,
    name: t.name || scheme.name,
    full_name: t.fullName || scheme.full_name,
    shortName: t.name || scheme.shortName || scheme.name,
    category: t.category || scheme.category,
    description: t.description || scheme.description,
    maxLoan: t.maxLoan || scheme.maxLoan || scheme.max_loan,
    subsidy: t.subsidy || scheme.subsidy,
    ministry: t.ministry || scheme.ministry,
    state: t.state || scheme.state,
    eligibility: t.eligibility || scheme.eligibility,
    benefits: t.benefits || scheme.benefits,
    documents: t.documents || scheme.documents
  };
};

module.exports = {
  SCHEME_TRANSLATIONS,
  getLocalizedScheme
};
